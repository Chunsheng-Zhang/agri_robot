// Uses a real FastAPI/ROS/OpenNav stack, but MUST point at web_test_runtime.py.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const base = process.env.AGRI_WEB_TEST_URL || 'http://127.0.0.1:15173'
const artifacts = path.resolve(__dirname, '../.diagnostics/web-workspace-e2e')
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw Error('Local synthetic test only')

;(async () => {
  const browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 1560, height: 1080 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    const marker = await page.request.get(`${base}/api/test-environment`)
    assert(marker.ok(), 'Refusing to control a backend without the synthetic runtime marker')
    const info = await marker.json()
    assert(info.synthetic === true && info.hardware === false && info.domain >= 200)
    fs.mkdirSync(artifacts, { recursive: true })
    const get = async route => (await page.request.get(`${base}${route}`)).json()
    const wait = async fn => {
      const deadline = Date.now() + 35000
      while (Date.now() < deadline) {
        if (await page.evaluate(fn)) return
        await new Promise(resolve => setTimeout(resolve, 60))
      }
      throw Error(`Timed out waiting for ${String(fn)}`)
    }
    await page.goto(`${base}/tasks`)
    await wait(() => document.body.innerText.includes('软件联调 · 模拟定位'))
    assert.equal(await page.locator('h1').innerText(), '多点导航')
    assert.equal(await page.getByRole('button', { name: '生成覆盖路径', exact: true }).count(), 0)
    assert.equal(await page.locator('.mode-buttons').getByRole('button', { name: '全覆盖作业', exact: true }).count(), 0)
    await page.locator('.mode-buttons').getByRole('button', { name: '多点导航', exact: true }).click()
    await wait(() => document.querySelector('.mode-selector strong').textContent === '多点导航')
    const context = await get('/api/workspace')
    await page.locator('.el-form-item').filter({ hasText: '任务名称' }).getByRole('textbox').fill('Web 页面多点任务')
    await page.getByPlaceholder('经度', { exact: true }).first().fill(String(context.origin.longitude + 0.00002))
    await page.getByPlaceholder('纬度', { exact: true }).first().fill(String(context.origin.latitude))
    await page.getByRole('button', { name: '保存任务', exact: true }).click()
    await wait(() => document.body.innerText.includes('已保存 · v1'))
    await page.getByRole('button', { name: '解除急停', exact: true }).first().click()
    await page.locator('.el-message-box').getByRole('button', { name: '确认复位', exact: true }).click()
    await page.getByRole('button', { name: '开始多点导航', exact: true }).click()
    await wait(() => document.querySelector('.task-controls').innerText.includes('运行中'))
    await page.getByRole('button', { name: '暂停任务', exact: true }).click()
    await wait(() => document.querySelector('.task-controls').innerText.includes('已暂停'))
    await page.goto(`${base}/planning`)
    await wait(() => document.body.innerText.includes('软件联调 · 模拟定位'))
    assert.equal(await page.locator('h1').innerText(), '全覆盖规划与跟踪')
    assert.equal((await get('/api/devices')).safety.mode, 'waypoint', 'Changing sections must not switch the robot mode')
    assert.equal(await page.getByRole('button', { name: '开始多点导航', exact: true }).count(), 0)
    assert.equal(await page.locator('.mission-list').getByText('Web 页面多点任务', { exact: true }).count(), 0)
    assert.equal(await page.getByRole('button', { name: '继续任务', exact: true }).isDisabled(), true)
    await page.goto(`${base}/tasks`)
    await wait(() => document.querySelector('.task-controls').innerText.includes('已暂停'))
    await page.getByRole('button', { name: '继续任务', exact: true }).click()
    await wait(() => document.querySelector('.task-controls').innerText.includes('运行中'))
    await page.locator('.mode-buttons').getByRole('button', { name: '基础待命', exact: true }).click()
    await page.locator('.el-message-box').getByRole('button', { name: '停止并切换', exact: true }).click()
    await wait(async () => (await (await fetch('/api/devices')).json()).safety.owner === '')

    await page.goto(`${base}/monitor`)
    assert.equal(await page.locator('.task-controls').count(), 0)
    await page.getByRole('button', { name: '启用 Web 遥控', exact: true }).click()
    await wait(() => document.body.innerText.includes('Web 遥控已启用'))
    const before = (await get('/api/robot/status')).position_x
    await page.getByRole('button', { name: '↑ 前进', exact: true }).hover()
    await page.mouse.down()
    await page.waitForTimeout(400)
    await page.mouse.up()
    await wait(async () => (await (await fetch('/api/devices')).json()).safety.linear === 0)
    const after = (await get('/api/robot/status')).position_x
    assert(after > before + 0.01, 'Held manual button should move the synthetic robot')
    await page.evaluate(() => window.dispatchEvent(new Event('blur')))
    await wait(async () => (await (await fetch('/api/devices')).json()).safety.owner === '')

    await page.goto(`${base}/planning`)
    const text = fs.readFileSync(path.join(__dirname, '../agri_robot_ws/src/agri_bringup/config/field.yaml'), 'utf8')
    const points = [...text.matchAll(/latitude:\s*([\d.]+),\s*longitude:\s*([\d.]+)/g)].map(match => [Number(match[2]), Number(match[1])])
    const boundary = { type: 'Polygon', coordinates: [[...points, points[0]]] }
    await page.locator('input[type=file]').setInputFiles({ name: 'test-field.geojson', mimeType: 'application/geo+json', buffer: Buffer.from(JSON.stringify(boundary)) })
    await page.locator('.el-form-item').filter({ hasText: '任务名称' }).getByRole('textbox').fill('Web 页面覆盖任务')
    await page.locator('.el-form-item').filter({ hasText: '最小转弯半径' }).getByRole('spinbutton').fill('0.65')
    await page.locator('.el-form-item').filter({ hasText: '最小转弯半径' }).getByRole('spinbutton').press('Tab')
    await page.getByRole('button', { name: '保存任务', exact: true }).click()
    await wait(() => document.body.innerText.includes('已保存 · v1'))
    await page.locator('.mode-buttons').getByRole('button', { name: '全覆盖作业', exact: true }).click()
    await page.getByRole('button', { name: '生成覆盖路径', exact: true }).click()
    await wait(async () => (await (await fetch('/api/workspace')).json()).active_run?.state === 'READY')
    assert((await get('/api/robot/path/reference')).count > 2)
    assert.equal((await get('/api/devices')).safety.owner, '')
    await page.waitForTimeout(600)
    await page.screenshot({ path: path.join(artifacts, 'planning.png'), fullPage: true })
    await page.getByRole('button', { name: '前往起点并开始覆盖', exact: true }).click()
    await wait(() => document.querySelector('.task-controls').innerText.includes('运行中'))
    await wait(() => document.querySelector('.task-controls').innerText.includes('前往覆盖起点（单点导航）'))
    assert.equal((await get('/api/devices')).safety.mode, 'coverage')
    await page.getByRole('button', { name: '取消任务', exact: true }).click()
    await wait(() => document.querySelector('.task-controls').innerText.includes('已取消'))
    const categoryRow = page.locator('.task-history').getByRole('row').filter({ hasText: 'Web 页面覆盖任务' }).first()
    await categoryRow.getByRole('link', { name: '下载任务数据', exact: true }).waitFor()
    assert.equal(await page.locator('.task-history').getByText('Web 页面多点任务', { exact: true }).count(), 0)
    await page.goto(`${base}/settings`)
    const row = page.getByRole('row').filter({ hasText: 'Web 页面覆盖任务' }).first()
    const downloaded = page.waitForEvent('download')
    await row.getByRole('link', { name: '下载任务数据', exact: true }).click()
    const download = await downloaded
    await download.saveAs(path.join(artifacts, 'archive.zip'))
    assert(fs.statSync(path.join(artifacts, 'archive.zip')).size > 1000)
    await page.goto(`${base}/devices`)
    await wait(() => document.body.innerText.includes('12.40 V'))
    await page.setViewportSize({ width: 390, height: 844 })
    await page.waitForTimeout(500)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2), 'Mobile page should not overflow horizontally')
    await page.screenshot({ path: path.join(artifacts, 'mobile.png'), fullPage: true })
    assert.deepEqual(errors, [])
    console.log('PASS: real Web→FastAPI→ROS mode switch; waypoint pause/resume; held manual control and blur stop; GeoJSON import; actual OpenNav planning and tracking; archive download; device telemetry; mobile layout')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
